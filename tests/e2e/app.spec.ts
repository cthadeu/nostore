import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
test('cadastro, e-mail, produto persistido e layout móvel pelo Compose', async ({ page, request, context }) => {
  const email = `e2e-${randomUUID()}@example.test`;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/cadastro');
  await page.getByLabel('Seu nome').fill('Teste Docker');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill('docker-e2e-password');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Criar minha conta' }).click();
  await expect(page.getByRole('heading', { name: 'Olá, Teste' })).toBeVisible();
  let mailId = '';
  await expect.poll(async () => {
    const response = await request.get('http://localhost:8025/api/v1/messages');
    const body = await response.json();
    mailId = body.messages.find((m: { To: Array<{ Address: string }> }) => m.To.some(to => to.Address === email))?.ID ?? '';
    return mailId;
  }, { timeout: 15_000 }).not.toBe('');
  const mail = await (await request.get(`http://localhost:8025/api/v1/message/${mailId}`)).json();
  const link = mail.Text.match(/http[^\s]+#token=[a-f0-9]+/)[0];
  await page.goto(link);
  await page.getByRole('button', { name: 'Confirmar meu e-mail' }).click();
  await expect(page.getByRole('status')).toContainText('E-mail confirmado');
  await page.getByRole('link', { name: 'Continuar' }).click();
  await page.getByRole('link', { name: '+ Novo produto', exact: true }).click();
  await page.getByLabel('Nome do produto').fill('Guia de teste Docker');
  await page.getByLabel('Descrição').fill('Produto criado no teste completo da aplicação em containers.');
  await page.getByLabel('Preço (R$)').fill('49.90');
  await page.getByRole('button', { name: 'Salvar produto' }).click();
  await expect(page.getByRole('status')).toContainText('Produto salvo');
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Guia de teste Docker' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Guia de teste Docker' })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Configurações', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Configurações', exact: true })).toBeVisible();
  await page.getByLabel('Nome do vendedor').fill('Estúdio Docker');
  await page.getByLabel('CPF', { exact: true }).fill('529.982.247-25');
  await page.getByRole('button', { name: 'Salvar alterações' }).click();
  await expect(page.getByRole('status')).toContainText('Perfil atualizado');
  await page.reload();
  await expect(page.getByLabel('Nome do vendedor')).toHaveValue('Estúdio Docker');
  await expect(page.getByText('Documento cadastrado: final 4725.', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Conectar Mercado Pago' })).toBeDisabled();
  await page.screenshot({ path: 'test-results/settings-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await expect(page.getByRole('link', { name: 'Configurações', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/settings-mobile.png', fullPage: true });
  await page.getByRole('link', { name: 'Visão geral', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Guia de teste Docker' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/dashboard-mobile.png', fullPage: true });
  // Publish and complete a digital purchase using the real ClamAV service.
  await page.getByRole('link').filter({ has: page.getByRole('heading', { name: 'Guia de teste Docker' }) }).click();
  await page.getByLabel('Imagem do produto').setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') });
  await page.getByLabel('Arquivo digital', { exact: true }).setInputFiles({ name: 'guia.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nnostore e2e digital content\n%%EOF') });
  await page.getByRole('button', { name: 'Salvar produto' }).click();
  await expect(page.getByText('Um arquivo já está salvo.', { exact: false })).toBeVisible({ timeout: 15000 });
  await page.getByRole('button', { name: 'Publicar produto', exact: true }).click();
  await expect(page.getByLabel('Link do checkout')).toBeVisible();
  const checkoutLink = await page.getByLabel('Link do checkout').inputValue();
  const buyer = await context.newPage();
  buyer.on('pageerror', error => errors.push(error.message));
  await buyer.setViewportSize({ width: 375, height: 812 });
  await buyer.goto(checkoutLink);
  await buyer.getByLabel('Nome completo').fill('Comprador Docker');
  const buyerEmail = `buyer-${randomUUID()}@example.test`;
  await buyer.getByLabel('E-mail para receber o produto').fill(buyerEmail);
  await buyer.getByLabel('CPF ou CNPJ').fill('52998224725');
  await buyer.getByRole('checkbox').check();
  expect(await buyer.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await buyer.screenshot({ path: 'test-results/checkout-mobile.png', fullPage: true });
  await buyer.getByRole('button', { name: 'Criar pedido de teste' }).click();
  await expect(buyer.getByText('Aguardando aprovação do vendedor', { exact: false })).toBeVisible();
  await expect(buyer).toHaveURL(/\/pedido$/);
  await expect(buyer.getByRole('button', { name: 'Baixar produto digital' })).toHaveCount(0);
  await page.goto('/pedidos');
  await page.getByRole('button', { name: 'Simular aprovação' }).click();
  await expect(buyer.getByRole('button', { name: 'Baixar produto digital' })).toBeVisible({ timeout: 15000 });
  const downloadEvent = buyer.waitForEvent('download');
  await buyer.getByRole('button', { name: 'Baixar produto digital' }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe('guia.pdf');
  expect((await readFile((await download.path())!, 'utf8'))).toContain('nostore e2e digital content');
  await expect.poll(async () => {
    const messages = await (await request.get('http://localhost:8025/api/v1/messages')).json();
    return messages.messages.filter((m: { To: Array<{ Address: string }> }) => m.To.some(to => to.Address === buyerEmail)).length;
  }, { timeout: 15000 }).toBe(3);
  await page.screenshot({ path: 'test-results/orders-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Simular reembolso' }).click();
  await buyer.getByRole('button', { name: 'Atualizar situação' }).click();
  await expect(buyer.getByText('Reembolsado', { exact: true })).toBeVisible({ timeout: 15000 });
  await expect(buyer.getByRole('button', { name: 'Baixar produto digital' })).toHaveCount(0);
  await buyer.close();
  await page.getByRole('button', { name: 'Sair da conta' }).click();
  await expect(page.getByRole('heading', { name: 'Bom ter você de volta.' })).toBeVisible();
  expect(errors).toEqual([]);
});
